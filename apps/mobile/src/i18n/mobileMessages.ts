export function translateMobileText(locale: ResolvedAppLocale, text: string): string {
  if (locale !== "ja") return text;
  const exact = JA_MOBILE_MESSAGES[text];
  if (exact !== undefined) return exact;
  if (text.startsWith("No threads in ")) {
    return `${text.slice("No threads in ".length)} にタスクはありません`;
  }
  const settled = /^Show more \((\d+) settled hidden\)$/.exec(text);
  if (settled) return `さらに表示（整理済みの非表示タスク ${settled[1]} 件）`;
  const days = /^After (\d+) days without activity$/.exec(text);
  if (days) return `${days[1]} 日間アクティビティがない場合`;
  return text;
}

